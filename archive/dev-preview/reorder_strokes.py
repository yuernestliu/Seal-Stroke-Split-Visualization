"""
对 data/glyphs.js 里所有字跑 stroke_ordering.order_strokes：
  - 重排 segments 数组顺序（按现代人书写直觉）
  - 重打 stroke_id 为 1..N
  - 同步 metrics.lengths 数组

会先备份原文件到 data/glyphs.js.bak。

执行：python scripts/_preview/reorder_strokes.py
"""
import json
import re
import sys
import shutil
from pathlib import Path

ROOT = Path(r"c:\Users\zzy\Pictures\作业\Seal-Stroke-Split-Visualization-main")
SRC_PKG = ROOT / "拆笔画修改" / "拆笔画_修改" / "src"

# 让 seal_stroke_split 可被 import
sys.path.insert(0, str(SRC_PKG))

from seal_stroke_split.stroke_ordering import order_strokes
from seal_stroke_split.types import StrokeSegment


def points_key(pts):
    """把 [[y,x], ...] 转成可哈希的 tuple-of-tuples"""
    return tuple((int(y), int(x)) for y, x in pts)


def parse_glyphs_js(path: Path) -> dict:
    """解析 window.GLYPH_DATA = { ... }; 格式"""
    text = path.read_text(encoding="utf-8")
    # 去掉块注释和行注释
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", "", text)
    m = re.search(
        r"window\.GLYPH_DATA\s*=\s*(\{.*\})\s*;?\s*$", text, flags=re.DOTALL
    )
    if not m:
        raise RuntimeError("找不到 window.GLYPH_DATA 块")
    return json.loads(m.group(1))


def dump_glyphs_js(path: Path, data: dict) -> None:
    """用标准 JSON 缩进写回"""
    body = json.dumps(data, ensure_ascii=False, indent=2)
    out = (
        "/* Generated by scripts/import_experiment.py. Do not hand-edit. */\n"
        f"window.GLYPH_DATA = {body};\n"
    )
    path.write_text(out, encoding="utf-8")


def reorder_one_glyph(glyph: dict) -> tuple[dict, bool]:
    """
    跑 order_strokes 重排 segments + 重打 id + 同步 lengths。
    返回 (新 glyph, 是否改变)。
    """
    old_segments = glyph["segments"]
    if len(old_segments) <= 1:
        return glyph, False

    # 用 points 序列做 key，建立 "原 segments 索引" 映射
    points_to_orig = {points_key(s["points"]): s for s in old_segments}

    # 转成 StrokeSegment
    seg_objs = [
        StrokeSegment(
            stroke_id=s["id"],
            points=[tuple(p) for p in s["points"]],
        )
        for s in old_segments
    ]

    # stroke_masks 用 None 占位（order_strokes 不参与计算，仅按 indices 重排后返回）
    fake_masks = [None] * len(seg_objs)
    _sorted_masks, sorted_segs = order_strokes(fake_masks, seg_objs)

    # 重建 segments + lengths
    new_segments = []
    new_lengths = []
    for new_id, seg in enumerate(sorted_segs, start=1):
        orig = points_to_orig[points_key(seg.points)]
        new_segments.append(
            {
                "id": new_id,
                "pointCount": orig["pointCount"],
                "pixelCount": orig["pixelCount"],
                "points": [list(p) for p in seg.points],
            }
        )
        new_lengths.append(orig["pointCount"])

    new_glyph = dict(glyph)
    new_glyph["segments"] = new_segments
    if "metrics" in new_glyph:
        new_metrics = dict(new_glyph["metrics"])
        new_metrics["lengths"] = new_lengths
        new_glyph["metrics"] = new_metrics

    old_ids = [s["id"] for s in old_segments]
    new_ids = [s["id"] for s in new_segments]
    changed = old_ids != new_ids
    return new_glyph, changed


def main():
    src = ROOT / "data" / "glyphs.js"
    bak = ROOT / "data" / "glyphs.js.bak"

    print(f"[1/4] 读取: {src}")
    data = parse_glyphs_js(src)
    glyphs = data["glyphs"]
    print(f"      共 {len(glyphs)} 个字")

    print(f"[2/4] 备份: {bak}")
    if bak.exists():
        print("      备份已存在，跳过")
    else:
        shutil.copy2(src, bak)
        print("      已备份")

    print("[3/4] 跑排序 ...")
    stats = {"changed": 0, "unchanged": 0}
    for i, glyph in enumerate(glyphs):
        new_glyph, changed = reorder_one_glyph(glyph)
        glyphs[i] = new_glyph
        if changed:
            stats["changed"] += 1
        else:
            stats["unchanged"] += 1

    print(f"      改变: {stats['changed']}, 不变: {stats['unchanged']}")

    print("[4/4] 写回 ...")
    dump_glyphs_js(src, data)
    print("      完成。")

    # 报告前 10 个改变最明显的字
    print()
    print("=== 抽样报告（前 10 个改变）===")
    shown = 0
    for glyph in glyphs:
        segs = glyph["segments"]
        if len(segs) >= 2 and segs[0]["id"] != 1:
            continue  # 已被重排
        if len(segs) <= 1:
            continue
        # 算 points 起点 y 排序 vs id 排序的一致性
        old_style = sorted(
            range(len(segs)), key=lambda j: min(p[0] for p in segs[j]["points"])
        )
        new_style = list(range(len(segs)))  # id 顺序
        if old_style == new_style:
            continue
        # 起点 y 序列
        starts = [
            (min(p[0] for p in s["points"]), min(p[1] for p in s["points"]))
            for s in segs
        ]
        print(f"  {glyph['id']}  segments={len(segs)}  起点 y/x = {starts}")
        shown += 1
        if shown >= 10:
            break


if __name__ == "__main__":
    main()
